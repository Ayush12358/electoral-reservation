"""Audit major manuscript quantitative claims against reproducible result artifacts.

This is deliberately a claim registry rather than a text scraper: every listed
claim identifies its artifact, computation, and the prose fragment expected in
PAPER.md.  Add a registry entry whenever a new headline numerical claim is added.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "experiments" / "results"
PAPER = ROOT / "PAPER.md"
OUTPUT = ROOT / "outputs" / "manuscript_consistency_audit.md"


def read_series(name: str) -> pd.Series:
    return pd.read_csv(RESULTS / name, index_col=0).iloc[:, 0]


def require_close(label: str, observed: float, expected: float, tolerance: float = 0.0006):
    if abs(observed - expected) > tolerance:
        raise AssertionError(f"{label}: observed {observed}, expected {expected}")


def main():
    paper = PAPER.read_text(encoding="utf-8")
    checks: list[tuple[str, str, str, bool]] = []

    core = read_series("summary_with_controls.csv")
    require_close("Core female coefficient", float(core["full_controls_female_coef"]), -0.5442)
    checks.append(("Core full-control female coefficient", "summary_with_controls.csv", "−0.54 pp", "−0.54 pp" in paper))

    renom = read_series("validation_renomination.csv")
    require_close("Renomination CV AUC", float(renom["cv_auc_mean"]), 0.6604)
    checks.append(("Renomination CV AUC", "validation_renomination.csv", "0.660", "CV AUC = 0.660" in paper))

    future = pd.read_csv(RESULTS / "tcpd_future_performance_validation.csv")
    vote = future.loc[future["outcome"] == "next_election_vote_share"].iloc[0]
    win = future.loc[future["outcome"] == "next_election_win"].iloc[0]
    require_close("Future vote-share coefficient", float(vote["capability_coefficient"]), -0.061153)
    require_close("Future-win odds ratio", float(win["capability_odds_ratio"]), 1.001377)
    checks.extend([
        ("Future vote-share criterion coefficient", "tcpd_future_performance_validation.csv", "−0.061 pp", "−0.061 pp" in paper),
        ("Future-win criterion odds ratio", "tcpd_future_performance_validation.csv", "1.001", "odds ratio is 1.001" in paper),
    ])

    fuzzy = pd.read_csv(RESULTS / "fuzzy_match_sensitivity.csv")
    fuzzy_all = fuzzy.loc[fuzzy["scenario"] == "exact_plus_fuzzy_score_ge_0.94"].iloc[0]
    if int(fuzzy_all["n_fuzzy"]) != 444:
        raise AssertionError("Fuzzy sensitivity does not contain the expected 444 candidate links")
    require_close("Accept-all fuzzy coefficient", float(fuzzy_all["female_coef"]), -0.654215)
    checks.append(("Accept-all fuzzy-link sensitivity", "fuzzy_match_sensitivity.csv", "−0.65 pp", "−0.65 pp" in paper))

    exit_sensitivity = pd.read_csv(RESULTS / "exit_test_sensitivity.csv")
    if len(exit_sensitivity) != 100:
        raise AssertionError(f"Expected 100 exit-test configurations, found {len(exit_sensitivity)}")
    if exit_sensitivity["five_condition_exit_pass"].any():
        raise AssertionError("An exit-test configuration unexpectedly passed all five conditions")
    checks.append(("Exit-test sensitivity design", "exit_test_sensitivity.csv", "100 combinations", "100 combinations" in paper))

    extended = read_series("extended_summary.csv")
    if int(extended["n_total"]) != 24380 or int(extended["n_female"]) != 1798:
        raise AssertionError("TCPD Lok Sabha sample totals differ from audited values")
    checks.append(("TCPD Lok Sabha panel size", "extended_summary.csv", "24,380 candidates (1,798 female, 7.4%)", "24,380 candidates (1,798 female, 7.4%)" in paper))

    vidhan = read_series("vidhansabha_summary.csv")
    require_close("Vidhan Sabha pooled female coefficient", float(vidhan["overall_female_coef"]), -0.4989)
    checks.append(("Vidhan Sabha pooled coefficient", "vidhansabha_summary.csv", "−0.50 pp", "−0.50 pp" in paper))

    failed_text = [label for label, _, _, present in checks if not present]
    if failed_text:
        raise AssertionError("Manuscript text missing audited claim(s): " + ", ".join(failed_text))

    lines = [
        "# Manuscript Consistency Audit",
        "",
        "Generated by `experiments/manuscript_consistency_audit.py`.",
        "",
        "## Scope",
        "",
        "Audits the major quantitative claims introduced or relied on by the current revision. It verifies both the saved-artifact value and the corresponding prose fragment in `PAPER.md`; it is not a substitute for source verification of external news, legal, or literature claims.",
        "",
        "## Verified claims",
        "",
        "| Claim | Artifact | Manuscript value | Status |",
        "|---|---|---|---|",
    ]
    lines.extend(f"| {label} | `{artifact}` | {value} | verified |" for label, artifact, value, _ in checks)
    lines.extend([
        "",
        "## Remaining audit scope",
        "",
        "- External-source claims require source-by-source verification.",
        "- Every newly added headline numerical claim must be added to this registry before submission.",
    ])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Verified {len(checks)} major quantitative claims. Wrote {OUTPUT}.")


if __name__ == "__main__":
    main()
